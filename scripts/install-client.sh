#!/usr/bin/env bash
# Set up the broom closet client on this machine (laptop, desktop, whatever).
#
# Needs client.py sitting next to this script or one directory up. Installs a
# `closet` command with the server address and passphrase already filled in,
# so joining is one word. Everything lives under $HOME; nothing system-wide
# except Tailscale, which is optional and asked about separately.
set -euo pipefail

BINDIR="$HOME/.local/bin"
LIBDIR="$HOME/.local/share/broom-closet"
SECRET="$HOME/.closet-secret"
HOST=""
PORT=7777
WANT_TAILSCALE=1

usage() {
	cat <<'USAGE'
usage: install-client.sh --host <address> [options]

  --host <addr>    server address (a 100.x.y.z Tailscale IP, or a LAN IP)
  --port <n>       default 7777
  --lan            same-network setup; skip Tailscale entirely
  --no-tailscale   alias for --lan
  -h, --help       this text

You will be prompted for the shared passphrase. Get it from whoever runs the
server; it is the contents of their ~/.closet-secret. To script it instead,
set $CLOSET_SECRET in the environment before running.
USAGE
}

while [ $# -gt 0 ]; do
	case "$1" in
		--host) HOST="${2:?--host needs a value}"; shift ;;
		--port) PORT="${2:?--port needs a value}"; shift ;;
		--lan|--no-tailscale) WANT_TAILSCALE=0 ;;
		-h|--help) usage; exit 0 ;;
		*) echo "unknown option: $1" >&2; usage >&2; exit 2 ;;
	esac
	shift
done

say()  { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
info() { printf '    %s\n' "$*"; }
warn() { printf '\033[33m    ! %s\033[0m\n' "$*"; }

if [ -z "$HOST" ]; then
	echo "error: --host is required" >&2
	echo >&2
	usage >&2
	exit 2
fi

# --- 1. python -------------------------------------------------------------
say "Checking Python"
if ! command -v python3 >/dev/null; then
	cat >&2 <<'MSG'
python3 is not installed. Install it, then re-run this script:

  Arch            sudo pacman -S python
  Debian/Ubuntu   sudo apt install python3
  Fedora          sudo dnf install python3
  macOS           brew install python    (or install Xcode command line tools)
MSG
	exit 1
fi
python3 - <<'PY' || exit 1
import sys
if sys.version_info < (3, 9):
    sys.exit(f"python 3.9+ required, found {sys.version.split()[0]}")
print(f"    python {sys.version.split()[0]} — ok")
PY
info "no pip packages needed; the client is standard library only"

# --- 2. find and install client.py ----------------------------------------
say "Installing the client"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC=""
for candidate in "$HERE/client.py" "$HERE/../client.py"; do
	[ -f "$candidate" ] && { SRC="$(cd "$(dirname "$candidate")" && pwd)/client.py"; break; }
done
if [ -z "$SRC" ]; then
	echo "error: cannot find client.py next to this script or one level up." >&2
	echo "Copy client.py into $HERE and re-run." >&2
	exit 1
fi

mkdir -p "$LIBDIR" "$BINDIR"
install -m 755 "$SRC" "$LIBDIR/client.py"
info "installed $LIBDIR/client.py"

# --- 3. passphrase ---------------------------------------------------------
say "Shared passphrase"
if [ -s "$SECRET" ]; then
	info "already present at $SECRET — keeping it"
	info "delete that file and re-run if the passphrase changed"
elif [ -n "${CLOSET_SECRET:-}" ]; then
	install -m 600 /dev/null "$SECRET"
	printf '%s' "$CLOSET_SECRET" > "$SECRET"
	chmod 600 "$SECRET"
	info "saved from \$CLOSET_SECRET to $SECRET (mode 600)"
elif [ ! -t 0 ] && [ ! -r /dev/tty ]; then
	warn "no terminal to prompt on; set \$CLOSET_SECRET or create $SECRET yourself"
else
	printf '    paste the passphrase (hidden): '
	read -rs pass </dev/tty
	printf '\n'
	if [ -z "$pass" ]; then
		warn "nothing entered; you will be prompted each time you connect"
	else
		install -m 600 /dev/null "$SECRET"
		printf '%s' "$pass" > "$SECRET"
		chmod 600 "$SECRET"
		info "saved to $SECRET (mode 600)"
	fi
	unset pass
fi

# --- 4. the `closet` wrapper ----------------------------------------------
say "Creating the 'closet' command"
cat > "$BINDIR/closet" <<WRAPEOF
#!/usr/bin/env bash
# Generated by install-client.sh — edit the two values below if they change.
exec python3 "$LIBDIR/client.py" "$HOST" "$PORT" \\
	\$([ -s "$SECRET" ] && printf '%s' "--secret-file $SECRET") "\$@"
WRAPEOF
chmod 755 "$BINDIR/closet"
info "installed $BINDIR/closet -> $HOST:$PORT"

case ":$PATH:" in
	*":$BINDIR:"*) info "$BINDIR is on your PATH" ;;
	*)
		warn "$BINDIR is NOT on your PATH. Add this to ~/.bashrc or ~/.zshrc:"
		warn "  export PATH=\"\$HOME/.local/bin:\$PATH\""
		warn "Until then, run it as: $BINDIR/closet"
		;;
esac

# --- 5. tailscale ---------------------------------------------------------
if [ "$WANT_TAILSCALE" -eq 1 ]; then
	say "Tailscale"
	if command -v tailscale >/dev/null; then
		info "already installed"
		if ! tailscale status >/dev/null 2>&1; then
			warn "installed but not logged in. Run:  sudo tailscale up"
			warn "Log into the SAME account that runs the server."
		else
			info "logged in and running"
		fi
	elif command -v pacman >/dev/null; then
		info "installing via pacman (needs sudo)"
		sudo pacman -S --needed --noconfirm tailscale
		sudo systemctl enable --now tailscaled
		warn "now run:  sudo tailscale up"
	else
		warn "Tailscale is not installed. Install it for your system:"
		warn "  Debian/Ubuntu/Fedora   curl -fsSL https://tailscale.com/install.sh | sh"
		warn "  macOS                  brew install --cask tailscale"
		warn "  Windows                https://tailscale.com/download/windows"
		warn "Review that install script before piping it to a shell."
		warn "Then:  sudo tailscale up   (same account as the server)"
	fi
else
	say "Skipping Tailscale (LAN mode)"
	info "you must be able to reach $HOST:$PORT on the local network"
fi

# --- done -----------------------------------------------------------------
say "Done"
info "Join the room with:   closet"
info "Override the nick:    closet --nick yourname"
info "Reachability check:   python3 -c \"import socket;socket.create_connection(('$HOST',$PORT),5);print('reachable')\""
